-- Lectura pública para el cliente web. Las escrituras del sincronizador
-- se realizan con la service role key almacenada solo en Supabase.
do $$
declare t text;
begin
  foreach t in array array[
    'competiciones','equipos','partidos','estadisticas_partido','cuotas_mercado',
    'equipo_competiciones'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', 'lectura_publica_' || t, t);
    execute format('create policy %I on public.%I for select to anon, authenticated using (true)',
      'lectura_publica_' || t, t);
    execute format('grant select on public.%I to anon, authenticated', t);
  end loop;
  alter table public.sincronizaciones enable row level security;
end $$;

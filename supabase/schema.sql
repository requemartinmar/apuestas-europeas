-- Esquema de Cancha / Apuestas Europeas.
-- Compatible con las tablas compartidas por el usuario y preparado para
-- las cuatro ligas domésticas y las tres competiciones UEFA.
create extension if not exists pgcrypto;

create table if not exists public.competiciones (
  id text primary key,
  nombre text not null,
  pais text,
  temporada_actual text,
  activo boolean default true,
  created_at timestamptz not null default now()
);

create table if not exists public.equipos (
  id bigint primary key,
  competid_id text references public.competiciones(id),
  nombre text not null,
  nombre_corto text,
  escudo_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.partidos (
  id bigint primary key,
  competid_id text references public.competiciones(id),
  temporada text not null,
  jornada integer not null default 0,
  fecha_utc timestamptz not null,
  equipo_local_id bigint references public.equipos(id),
  equipo_visitante_id bigint references public.equipos(id),
  goles_local integer,
  goles_visitante integer,
  estado text default 'SCHEDULED',
  created_at timestamptz not null default now()
);

create table if not exists public.estadisticas_partido (
  id bigint generated by default as identity primary key,
  partido_id bigint references public.partidos(id) on delete cascade,
  posesion_local numeric,
  posesion_visitante numeric,
  tiros_puerta_local integer,
  tiros_puerta_visitante integer,
  corners_local integer,
  corners_visitante integer,
  tarjetas_amarillas_local integer,
  tarjetas_amarillas_visitante integer,
  tarjetas_rojas_local integer,
  tarjetas_rojas_visitante integer,
  fuente text,
  capturado_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.cuotas_mercado (
  id bigint generated by default as identity primary key,
  partido_id bigint references public.partidos(id) on delete cascade,
  casa_apuestas text not null,
  mercado text not null,
  seleccion text not null,
  cuota numeric not null check (cuota > 1),
  proveedor text not null,
  hora_captura timestamptz not null,
  created_at timestamptz not null default now()
);

-- Un equipo puede participar a la vez en su liga doméstica y en UEFA.
-- Esta tabla resuelve la relación muchos-a-muchos sin duplicar equipos.
create table if not exists public.equipo_competiciones (
  equipo_id bigint not null references public.equipos(id) on delete cascade,
  competicion_id text not null references public.competiciones(id) on delete cascade,
  temporada text not null,
  created_at timestamptz not null default now(),
  primary key (equipo_id, competicion_id, temporada)
);

-- Metadatos para guardar la etiqueta real de rondas UEFA y limitar
-- reconsultas de estadísticas. jornada=0 representa una ronda sin número.
alter table public.partidos add column if not exists jornada_nombre text;
alter table public.partidos add column if not exists estadisticas_primera_captura_at timestamptz;
alter table public.partidos add column if not exists estadisticas_confirmada_at timestamptz;
alter table public.partidos add column if not exists estadisticas_estado text not null default 'PENDING'
  check (estadisticas_estado in ('PENDING','AVAILABLE','EMPTY_RESPONSE'));
alter table public.partidos add column if not exists fuente text;
alter table public.partidos add column if not exists sincronizado_at timestamptz;
alter table public.partidos add column if not exists raw_payload jsonb not null default '{}'::jsonb;

create table if not exists public.sincronizaciones (
  id bigint generated by default as identity primary key,
  proveedor text not null,
  competicion_id text references public.competiciones(id),
  temporada text,
  tipo text not null,
  estado text not null check (estado in ('RUNNING','SUCCESS','PARTIAL','FAILED')),
  iniciada_at timestamptz not null default now(),
  terminada_at timestamptz,
  partidos_vistos integer not null default 0,
  partidos_guardados integer not null default 0,
  estadisticas_guardadas integer not null default 0,
  detalle jsonb not null default '{}'::jsonb,
  error text
);

create index if not exists partidos_competicion_temporada_jornada_idx
  on public.partidos (competid_id, temporada, jornada_nombre, fecha_utc);
create index if not exists partidos_estado_fecha_idx
  on public.partidos (estado, fecha_utc desc);
create index if not exists estadisticas_partido_latest_idx
  on public.estadisticas_partido (partido_id, capturado_at desc);
create index if not exists cuotas_partido_mercado_idx
  on public.cuotas_mercado (partido_id, mercado, hora_captura desc);


create table if not exists public.oddspapi_fixture_map (
  fixture_id text primary key,
  partido_id bigint not null references public.partidos(id) on delete cascade,
  equipo_local text not null,
  equipo_visitante text not null,
  kickoff timestamptz not null,
  status_id integer,
  proveedor text not null default 'OddsPapi',
  updated_at timestamptz not null default now()
);
create index if not exists oddspapi_fixture_map_partido_idx on public.oddspapi_fixture_map(partido_id);

create table if not exists public.cuotas_historicas_oddspapi (
  id bigint generated by default as identity primary key,
  partido_id bigint not null references public.partidos(id) on delete cascade,
  fixture_id text not null,
  bookmaker_slug text not null check (bookmaker_slug in ('bet365','betfair-ex')),
  bookmaker_name text not null,
  history jsonb not null,
  fetched_at timestamptz not null default now(),
  source text not null default 'OddsPapi'
);
create index if not exists cuotas_historicas_oddspapi_match_idx on public.cuotas_historicas_oddspapi(partido_id,bookmaker_slug,fetched_at desc);
create index if not exists cuotas_historicas_oddspapi_fixture_idx on public.cuotas_historicas_oddspapi(fixture_id,bookmaker_slug);

create table if not exists public.oddspapi_historical_cache (
  fixture_id text not null,
  bookmaker_filter text not null,
  etag text,
  response_body jsonb not null,
  fetched_at timestamptz not null default now(),
  status_id integer,
  primary key (fixture_id,bookmaker_filter)
);


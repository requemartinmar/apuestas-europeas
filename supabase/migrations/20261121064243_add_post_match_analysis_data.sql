create unique index if not exists estadisticas_partido_partido_id_uidx
  on public.estadisticas_partido(partido_id);

alter table public.partidos
  add column if not exists eventos_estado text not null default 'PENDING',
  add column if not exists eventos_confirmados_at timestamptz;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.partidos'::regclass
      and conname = 'partidos_eventos_estado_check'
  ) then
    alter table public.partidos
      add constraint partidos_eventos_estado_check
      check (eventos_estado in ('PENDING','AVAILABLE','EMPTY_RESPONSE'));
  end if;
end $$;

create table if not exists public.partido_eventos (
  id bigint generated by default as identity primary key,
  partido_id bigint not null references public.partidos(id) on delete cascade,
  proveedor text not null,
  fixture_id bigint not null,
  event_key text not null,
  minuto integer,
  minuto_extra integer,
  equipo text,
  lado_equipo text not null default 'unknown' check (lado_equipo in ('local','visitante','unknown')),
  jugador_id bigint,
  jugador text,
  asistente_id bigint,
  asistente text,
  tipo text,
  detalle text,
  comentario text,
  raw_payload jsonb not null default '{}'::jsonb,
  capturado_at timestamptz not null default now(),
  unique (partido_id, proveedor, event_key)
);

create index if not exists partido_eventos_match_minute_idx
  on public.partido_eventos(partido_id, minuto, minuto_extra);

alter table public.partido_eventos enable row level security;
grant select on public.partido_eventos to anon, authenticated;
grant all on public.partido_eventos to service_role;

drop policy if exists "lectura_publica_partido_eventos" on public.partido_eventos;
create policy "lectura_publica_partido_eventos"
  on public.partido_eventos for select to anon, authenticated using (true);

create table if not exists public.partido_alineaciones (
  id bigint generated by default as identity primary key,
  partido_id bigint not null references public.partidos(id) on delete cascade,
  proveedor text not null default 'API-Football',
  fixture_id bigint not null,
  equipo_id bigint,
  equipo text not null,
  jugador_id bigint not null,
  jugador text not null,
  dorsal integer,
  posicion text,
  posicion_campo text,
  titular boolean not null default false,
  formacion text,
  entrenador_id bigint,
  entrenador text,
  raw_payload jsonb not null default '{}'::jsonb,
  capturado_at timestamptz not null default now(),
  constraint partido_alineaciones_partido_proveedor_jugador_key
    unique (partido_id, proveedor, jugador_id)
);
create index if not exists partido_alineaciones_match_team_idx
  on public.partido_alineaciones(partido_id, equipo_id, titular desc);
create index if not exists partido_alineaciones_player_idx
  on public.partido_alineaciones(jugador_id, capturado_at desc);
create index if not exists player_match_stats_team_date_idx
  on public.player_match_stats(team_id, match_date desc);


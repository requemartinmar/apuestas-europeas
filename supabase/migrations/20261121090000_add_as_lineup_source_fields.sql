alter table public.partido_alineaciones
  add column if not exists fuente_url text,
  add column if not exists minuto_entrada integer;

create table if not exists public.press_match_sync_runs (
  id bigint generated by default as identity primary key,
  provider text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running',
  pages_fetched integer not null default 0,
  matches_found integer not null default 0,
  lineups_saved integer not null default 0,
  details jsonb not null default '{}'::jsonb
);

alter table public.press_match_sync_runs enable row level security;
revoke all on public.press_match_sync_runs from anon, authenticated;
grant all on public.press_match_sync_runs to service_role;

create index if not exists idx_press_match_sync_runs_started_at
  on public.press_match_sync_runs (started_at desc);

grant select on public.partido_alineaciones to anon, authenticated;

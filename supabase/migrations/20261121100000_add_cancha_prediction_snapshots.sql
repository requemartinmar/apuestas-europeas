create table if not exists public.cancha_prediction_snapshots (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.partidos(id) on delete cascade,
  competition_id text,
  kickoff_at timestamptz not null,
  home_team text not null,
  away_team text not null,
  model_version text not null default 'cancha-poisson-v1',
  prediction_payload jsonb not null,
  actual_payload jsonb not null default '{}'::jsonb,
  status text not null default 'PENDING' check (status in ('PENDING','SETTLED')),
  captured_at timestamptz not null default now(),
  settled_at timestamptz,
  constraint cancha_prediction_snapshots_match_model_uidx unique (match_id, model_version),
  constraint cancha_prediction_snapshots_prediction_object check (jsonb_typeof(prediction_payload) = 'object'),
  constraint cancha_prediction_snapshots_actual_object check (jsonb_typeof(actual_payload) = 'object')
);

create index if not exists cancha_prediction_snapshots_kickoff_idx
  on public.cancha_prediction_snapshots(kickoff_at desc);
create index if not exists cancha_prediction_snapshots_status_idx
  on public.cancha_prediction_snapshots(status, kickoff_at desc);

alter table public.cancha_prediction_snapshots enable row level security;
revoke all on public.cancha_prediction_snapshots from anon, authenticated;
grant select, insert on public.cancha_prediction_snapshots to anon, authenticated;
grant all on public.cancha_prediction_snapshots to service_role;
grant usage, select on sequence public.cancha_prediction_snapshots_id_seq to anon, authenticated, service_role;

drop policy if exists "Cancha snapshots public read" on public.cancha_prediction_snapshots;
create policy "Cancha snapshots public read"
  on public.cancha_prediction_snapshots for select
  to anon, authenticated
  using (true);

drop policy if exists "Cancha can capture future model snapshots" on public.cancha_prediction_snapshots;
create policy "Cancha can capture future model snapshots"
  on public.cancha_prediction_snapshots for insert
  to anon, authenticated
  with check (
    model_version = 'cancha-poisson-v1'
    and captured_at <= now()
    and captured_at >= now() - interval '2 minutes'
    and jsonb_typeof(prediction_payload) = 'object'
    and exists (
      select 1
      from public.partidos p
      where p.id = match_id
        and p.competid_id is not distinct from competition_id
        and p.fecha_utc = kickoff_at
        and p.fecha_utc > now()
        and p.estado = 'SCHEDULED'
    )
  );

create or replace function public.refresh_cancha_prediction_snapshot()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_match_id bigint;
  v_match record;
  v_stats record;
  v_actual jsonb;
begin
  if tg_table_name = 'partidos' then
    v_match_id := new.id;
  else
    v_match_id := new.partido_id;
  end if;

  select id, estado, goles_local, goles_visitante
    into v_match
  from public.partidos
  where id = v_match_id;

  if not found or v_match.estado <> 'FINISHED'
     or v_match.goles_local is null or v_match.goles_visitante is null then
    return new;
  end if;

  select *
    into v_stats
  from public.estadisticas_partido
  where partido_id = v_match_id
  limit 1;

  v_actual := jsonb_build_object(
    'home_goals', v_match.goles_local,
    'away_goals', v_match.goles_visitante,
    'total_goals', v_match.goles_local + v_match.goles_visitante,
    'result', case
      when v_match.goles_local > v_match.goles_visitante then 'home'
      when v_match.goles_local = v_match.goles_visitante then 'draw'
      else 'away'
    end
  );

  if v_stats.partido_id is not null then
    if v_stats.corners_local is not null and v_stats.corners_visitante is not null then
      v_actual := v_actual || jsonb_build_object('corners_total', v_stats.corners_local + v_stats.corners_visitante);
    end if;
    if v_stats.tiros_puerta_local is not null and v_stats.tiros_puerta_visitante is not null then
      v_actual := v_actual || jsonb_build_object('shots_on_target_total', v_stats.tiros_puerta_local + v_stats.tiros_puerta_visitante);
    end if;
    if (v_stats.tarjetas_amarillas_local is not null or v_stats.tarjetas_rojas_local is not null)
       and (v_stats.tarjetas_amarillas_visitante is not null or v_stats.tarjetas_rojas_visitante is not null) then
      v_actual := v_actual || jsonb_build_object(
        'cards_total',
        coalesce(v_stats.tarjetas_amarillas_local, 0) + coalesce(v_stats.tarjetas_rojas_local, 0)
        + coalesce(v_stats.tarjetas_amarillas_visitante, 0) + coalesce(v_stats.tarjetas_rojas_visitante, 0)
      );
    end if;
  end if;

  update public.cancha_prediction_snapshots
  set actual_payload = v_actual,
      status = 'SETTLED',
      settled_at = coalesce(settled_at, now())
  where match_id = v_match_id;

  return new;
end;
$$;

drop trigger if exists cancha_snapshot_settle_from_match on public.partidos;
create trigger cancha_snapshot_settle_from_match
  after update of estado, goles_local, goles_visitante on public.partidos
  for each row execute function public.refresh_cancha_prediction_snapshot();

drop trigger if exists cancha_snapshot_refresh_from_stats on public.estadisticas_partido;
create trigger cancha_snapshot_refresh_from_stats
  after insert or update on public.estadisticas_partido
  for each row execute function public.refresh_cancha_prediction_snapshot();

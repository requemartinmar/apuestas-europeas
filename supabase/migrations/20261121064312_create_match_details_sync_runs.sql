create table if not exists public.match_details_sync_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running' check (status in ('running','success','partial','failed','skipped')),
  api_requests integer not null default 0 check (api_requests >= 0),
  fixtures_seen integer not null default 0,
  fixtures_enriched integer not null default 0,
  statistics_saved integer not null default 0,
  events_saved integer not null default 0,
  details jsonb not null default '{}'::jsonb
);
alter table public.match_details_sync_runs enable row level security;
grant all on public.match_details_sync_runs to service_role;
